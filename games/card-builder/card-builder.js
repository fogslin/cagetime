  function simBout(a, b, an, rr) {
    var ra = rating(a, b), rb = rating(b, a), pA = Math.min(0.88, Math.max(0.12, 1 / (1 + Math.exp(-(ra - rb) / 8))));
    var aw = rr() < pA, w = aw ? a : b, l = aw ? b : a;
    var W = w.rec ? Math.max(1, w.rec[0]) : 1, Lf = l.rec ? Math.max(1, l.rec[0] + l.rec[1]) : 1;
    var koS = w.wm ? w.wm[0] / W : 0.3, subS = w.wm ? w.wm[1] / W : 0.2;
    var lKO = l.lm ? l.lm[0] / Lf : 0.1, lSUB = l.lm ? l.lm[1] / Lf : 0.08;
    var pKO = Math.min(0.75, 0.55 * koS + 1.2 * lKO), pSUB = Math.min(0.6, 0.55 * subS + 1.2 * lSUB);
    var fin = pKO + pSUB; if (fin > 0.85) { pKO *= 0.85 / fin; pSUB *= 0.85 / fin; }
    var rounds = an.five ? 5 : 3, x = rr(), method = x < pKO ? 'KO' : x < pKO + pSUB ? 'SUB' : 'DEC';
    var rw = [0.38, 0.27, 0.18, 0.1, 0.07].slice(0, rounds), sum = rw.reduce(function (s, v) { return s + v; }, 0), y = rr() * sum, rd = 1;
    for (var i = 0; i < rw.length; i++) { if (y < rw[i]) { rd = i + 1; break; } y -= rw[i]; }
    var secs = 10 + Math.floor(rr() * 289), time = Math.floor(secs / 60) + ':' + ('0' + secs % 60).slice(-2);
    var pbp = [], usedT = {}, lastR = method === 'DEC' ? rounds : rd;
    for (var r = 1; r <= lastR; r++) {
      if (r === lastR && method !== 'DEC') break;
      var x2 = rr(), who = x2 < 0.62 ? w : l, opp = who === w ? l : w;
      var t = x2 > 0.9 ? pickU(TPL.close, usedT, rr) : pickU(tpl(who), usedT, rr);
      pbp.push('R' + r + ': ' + fill(t, { X: short(who.n), Y: short(opp.n), s: pickT(STR, rr), h: pickT(HEAD, rr), u: pickT(SUBS, rr), r: r }));
    }
    var how, s = pickT(STR, rr), u = pickT(SUBS, rr);
    if (method === 'KO') {
      pbp.push('R' + rd + ': ' + short(w.n) + ' ' + pickT(['drops ' + short(l.n) + ' with a ' + s + ' and swarms until the referee steps in', 'lands a clean ' + s + ' and ' + short(l.n) + ' crumbles', 'backs ' + short(l.n) + ' to the fence and a ' + s + ' ends it'], rr) + ' at ' + time + '.');
      how = 'KO/TKO (' + s + '), R' + rd + ' ' + time;
    } else if (method === 'SUB') {
      pbp.push('R' + rd + ': ' + short(w.n) + ' ' + pickT(['takes the back in a scramble and sinks in a ' + u, 'hits a takedown, passes, and locks up a ' + u, 'catches ' + short(l.n) + ' on the way up with a ' + u], rr) + '. ' + short(l.n) + ' taps at ' + time + '.');
      how = 'Submission (' + u + '), R' + rd + ' ' + time;
    } else {
      var k = rr(), typ = k < 0.72 ? 'unanimous' : k < 0.94 ? 'split' : 'majority', cards;
      cards = typ === 'unanimous' ? (rounds === 5 ? ['49-46', '48-47', '49-46'] : ['29-28', '30-27', '29-28']) : typ === 'split' ? (rounds === 5 ? ['48-47', '47-48', '48-47'] : ['29-28', '28-29', '29-28']) : (rounds === 5 ? ['48-47', '48-47', '47-47'] : ['29-28', '29-28', '28-28']);
      pbp.push('After ' + rounds + ' rounds it goes to the judges: ' + w.n + ' wins by ' + typ + ' decision (' + cards.join(', ') + ').');
      how = 'Decision (' + typ + ')';
      rd = rounds; time = '5:00';
    }
    return { a: a.id, b: b.id, w: w.id, l: l.id, how: how, pbp: pbp, method: method, rd: rd, time: time, pW: Math.round((aw ? pA : 1 - pA) * 100), hype: an.hype };
  }
