/* CageTime — UFC Fighter Trivia. Plain JS, no build step. Questions come from questions.json
   (generated by cagetime-tools/games/build_trivia.py from the site's own data). */
(function () {
  'use strict';
  var V = '20261018e';
  var $ = function (id) { return document.getElementById(id); };
  var esc = function (s) { return String(s == null ? '' : s).replace(/[&<>"']/g, function (c) { return { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]; }); };
  var MODES = {
    e: { name: 'Easy', mult: 1, secs: 20 },
    m: { name: 'Medium', mult: 1.5, secs: 17 },
    h: { name: 'Hard', mult: 2, secs: 15 },
    daily: { name: 'Daily challenge', mult: null, secs: 18 }
  };
  var TYPES = {
    champion: 'Champions', rank: 'Rankings', division: 'Divisions', recordholder: 'Record holder', bout: 'Results', method: 'Method & round',
    firstwin: 'First UFC win', physical: 'Tale of the tape', country: 'Nationality', nickname: 'Nicknames', stance: 'Stance',
    record: 'Career record', streak: 'Streaks', finish: 'Finish rate', neverlost: 'Durability', higherlower: 'Higher or lower',
    statline: 'Guess the fighter', history: 'UFC history',
    title: 'Title history', event: 'Fight results', era: 'Which year?', tuf: 'The Ultimate Fighter', tournament: 'Early tournaments',
    hof: 'Hall of Fame', records: 'UFC records'
  };
  var DNAME = { e: 'Easy', m: 'Medium', h: 'Hard' };
  var ROUND = 10;
  var store = {
    get: function (k, d) { try { var v = localStorage.getItem(k); return v == null ? d : JSON.parse(v); } catch (e) { return d; } },
    set: function (k, v) { try { localStorage.setItem(k, JSON.stringify(v)); } catch (e) { /* private mode */ } }
  };

  // ---------- seeded RNG (mulberry32) ----------
  function hash(str) { var h = 1779033703 ^ str.length; for (var i = 0; i < str.length; i++) { h = Math.imul(h ^ str.charCodeAt(i), 3432918353); h = h << 13 | h >>> 19; } return (h >>> 0); }
  function rng(seed) { var a = seed >>> 0; return function () { a = a + 0x6D2B79F5 | 0; var t = Math.imul(a ^ a >>> 15, 1 | a); t = t + Math.imul(t ^ t >>> 7, 61 | t) ^ t; return ((t ^ t >>> 14) >>> 0) / 4294967296; }; }
  function shuffle(a, r) { r = r || Math.random; for (var i = a.length - 1; i > 0; i--) { var j = Math.floor(r() * (i + 1)); var t = a[i]; a[i] = a[j]; a[j] = t; } return a; }
  function todayUTC() { return new Date().toISOString().slice(0, 10); }

  // ---------- sound (Web Audio, muted by default) ----------
  var sound = store.get('ct-trivia-sound', false), actx = null;
  function beep(freqs, dur, type) {
    if (!sound) return;
    try {
      actx = actx || new (window.AudioContext || window.webkitAudioContext)();
      var t = actx.currentTime;
      freqs.forEach(function (f, i) {
        var o = actx.createOscillator(), g = actx.createGain();
        o.type = type || 'sine'; o.frequency.value = f;
        g.gain.setValueAtTime(0.0001, t + i * dur); g.gain.exponentialRampToValueAtTime(0.18, t + i * dur + 0.02);
        g.gain.exponentialRampToValueAtTime(0.0001, t + (i + 1) * dur);
        o.connect(g); g.connect(actx.destination); o.start(t + i * dur); o.stop(t + (i + 1) * dur + 0.05);
      });
    } catch (e) { /* audio unavailable */ }
  }
  var sfx = {
    right: function () { beep([660, 880], 0.09, 'triangle'); },
    wrong: function () { beep([220, 160], 0.14, 'sawtooth'); },
    tick: function () { beep([1200], 0.03, 'square'); },
    done: function () { beep([523, 659, 784, 1046], 0.11, 'triangle'); }
  };
  function renderSound() { var b = $('tv-sound'); b.textContent = 'Sound: ' + (sound ? 'on' : 'off'); b.setAttribute('aria-pressed', sound ? 'true' : 'false'); }

  // ---------- state ----------
  var BANK = [], META = {}, S = null, timer = null;

  function show(id) {
    ['tv-start', 'tv-play', 'tv-results'].forEach(function (s) { $(s).classList.toggle('is-on', s === id); });
    window.scrollTo(0, 0);
  }
  function fmt(n) { return Math.round(n).toLocaleString('en-US'); }

  function renderStart() {
    var best = store.get('ct-trivia-best', {});
    document.querySelectorAll('[data-best]').forEach(function (el) {
      var k = el.getAttribute('data-best'); el.textContent = best[k] ? 'Best: ' + fmt(best[k]) : 'Best: —';
    });
    var d = store.get('ct-trivia-daily', null), t = todayUTC();
    $('tv-daily-sub').textContent = 'The same 10 questions for everyone on ' + t + ' (UTC). Mixed difficulty.';
    $('tv-daily-status').textContent = d && d.date === t ? 'Done: ' + fmt(d.score) + ' pts\nPlay again for fun' : 'Not played yet';
    var c = META.by_difficulty || {};
    $('tv-bank').textContent = BANK.length ? fmt(BANK.length) + ' questions in the bank (' + (c.e || 0) + ' easy, ' + (c.m || 0) + ' medium, ' + (c.h || 0) + ' hard)' : '';
    renderSound();
  }

  // pick 10: prefer unseen, max 2 per type, no repeated question text
  function pick(list, n, r, seen) {
    var pool = shuffle(list.slice(), r);
    if (seen) pool.sort(function (a, b) { return (seen[a.id] ? 1 : 0) - (seen[b.id] ? 1 : 0); });
    var out = [], perType = {}, texts = {};
    for (var pass = 0; pass < 2 && out.length < n; pass++) {
      for (var i = 0; i < pool.length && out.length < n; i++) {
        var q = pool[i];
        if (out.indexOf(q) >= 0 || texts[q.q]) continue;
        if (pass === 0 && (perType[q.t] || 0) >= 2) continue;
        out.push(q); perType[q.t] = (perType[q.t] || 0) + 1; texts[q.q] = 1;
      }
    }
    return out;
  }

  function start(mode) {
    var r, qs, seen = store.get('ct-trivia-seen', {});
    if (mode === 'daily') {
      var day = todayUTC();
      r = rng(hash('cagetime-daily-' + day));
      var byD = { e: [], m: [], h: [] };
      BANK.forEach(function (q) { byD[q.d].push(q); });
      // sort by id first so every visitor starts from the same order
      ['e', 'm', 'h'].forEach(function (k) { byD[k].sort(function (a, b) { return a.id - b.id; }); });
      qs = pick(byD.e, 3, r).concat(pick(byD.m, 4, r)).concat(pick(byD.h, 3, r));
    } else {
      r = Math.random;
      qs = pick(BANK.filter(function (q) { return q.d === mode; }), ROUND, r, seen);
    }
    S = {
      mode: mode, day: mode === 'daily' ? todayUTC() : null, qs: qs, i: 0, score: 0, streak: 0, best: 0, right: 0,
      log: [], r: r
    };
    $('tv-modelabel').textContent = MODES[mode].name;
    show('tv-play');
    ask();
  }

  function ask() {
    var q = S.qs[S.i], m = MODES[S.mode];
    var choices = shuffle([q.a].concat(q.w), S.mode === 'daily' ? S.r : Math.random);
    S.cur = { q: q, choices: choices, t0: performance.now(), secs: m.secs, done: false, lastTick: m.secs };
    $('tv-qnum').textContent = (S.i + 1) + '/' + S.qs.length;
    $('tv-prog').style.width = (S.i / S.qs.length * 100) + '%';
    $('tv-type').textContent = TYPES[q.t] || 'Trivia';
    $('tv-qdiff').textContent = S.mode === 'daily' ? DNAME[q.d] + ' x' + MODES[q.d].mult : '';
    $('tv-q').textContent = q.q;
    var img = $('tv-qimg');
    if (q.p) { img.src = '../../img/fighters/' + q.p; img.hidden = false; } else { img.hidden = true; img.removeAttribute('src'); }
    var ol = $('tv-choices'); ol.innerHTML = '';
    choices.forEach(function (c, i) {
      var li = document.createElement('li'), b = document.createElement('button');
      b.type = 'button'; b.innerHTML = '<span class="k">' + 'ABCD'[i] + '</span><span class="c">' + esc(c) + '</span>';
      b.setAttribute('data-i', i);
      b.addEventListener('click', function () { answer(i); });
      li.appendChild(b); ol.appendChild(li);
    });
    $('tv-explain').hidden = true;
    var card = $('tv-card'); card.classList.remove('enter', 'shake'); void card.offsetWidth; card.classList.add('enter');
    $('tv-time').parentNode.classList.remove('low');
    cancelAnimationFrame(timer); timer = requestAnimationFrame(tick);
    var first = ol.querySelector('button'); if (first && !matchMedia('(hover:none)').matches) first.focus({ preventScroll: true });
  }

  function tick() {
    if (!S || !S.cur || S.cur.done) return;
    var el = (performance.now() - S.cur.t0) / 1000, left = Math.max(0, S.cur.secs - el);
    $('tv-time').style.width = (left / S.cur.secs * 100) + '%';
    var whole = Math.ceil(left);
    $('tv-secs').textContent = whole;
    if (left <= 5) { $('tv-time').parentNode.classList.add('low'); if (whole < S.cur.lastTick) { S.cur.lastTick = whole; sfx.tick(); } }
    if (left <= 0) { answer(-1); return; }
    timer = requestAnimationFrame(tick);
  }

  function answer(i) {
    var c = S.cur; if (!c || c.done) return;
    c.done = true; cancelAnimationFrame(timer);
    var q = c.q, elapsed = (performance.now() - c.t0) / 1000, left = Math.max(0, c.secs - elapsed);
    var ok = i >= 0 && c.choices[i] === q.a;
    var mult = S.mode === 'daily' ? MODES[q.d].mult : MODES[S.mode].mult, pts = 0;
    if (ok) {
      S.streak++; S.right++; S.best = Math.max(S.best, S.streak);
      var speed = Math.round(100 * left / c.secs), sb = Math.min(100, 25 * (S.streak - 1));
      pts = Math.round((100 + speed + sb) * mult);
      S.score += pts;
    } else { S.streak = 0; }
    S.log.push({ q: q, pick: i >= 0 ? c.choices[i] : null, ok: ok, pts: pts, timeout: i < 0 });
    var btns = $('tv-choices').querySelectorAll('button');
    btns.forEach(function (b, k) {
      b.disabled = true;
      if (c.choices[k] === q.a) b.classList.add('right');
      else if (k === i) b.classList.add('wrong'); else b.classList.add('dim');
    });
    var v = $('tv-verdict');
    v.className = 'tv-verdict ' + (ok ? 'ok' : 'no');
    v.textContent = ok ? 'Correct! +' + fmt(pts) : (i < 0 ? 'Time! The answer: ' + q.a : 'Not quite. The answer: ' + q.a);
    $('tv-xtext').textContent = q.x;
    $('tv-rimgs').innerHTML = (q.rp || []).map(function (p) { return '<img src="../../img/fighters/' + esc(p) + '" alt="" width="52" height="52" loading="lazy">'; }).join('');
    $('tv-src').innerHTML = srcHtml(q.src);
    $('tv-explain').hidden = false;
    $('tv-next').textContent = S.i + 1 < S.qs.length ? 'Next question' : 'See results';
    $('tv-score').textContent = fmt(S.score);
    var st = $('tv-streak'); st.textContent = S.streak; st.classList.toggle('hot', S.streak >= 3);
    st.classList.remove('bump'); void st.offsetWidth; if (ok) st.classList.add('bump');
    if (ok) { pop('+' + fmt(pts)); sfx.right(); }
    else { var card = $('tv-card'); card.classList.remove('shake', 'enter'); void card.offsetWidth; card.classList.add('shake'); sfx.wrong(); }
    $('tv-next').focus({ preventScroll: true });
    $('tv-explain').scrollIntoView({ block: 'nearest', behavior: 'smooth' });
  }

  function srcHtml(src) {
    var links = [], data = false;
    (src || []).forEach(function (s) {
      if (/^https?:\/\//.test(s)) {
        var label = s.replace(/^https?:\/\/(www\.)?/, '').replace(/^en\.wikipedia\.org\/wiki\//, 'Wikipedia: ').replace(/_/g, ' ');
        links.push('<a href="' + esc(s) + '" target="_blank" rel="noopener">' + esc(decodeURIComponent(label)) + '</a>');
      } else data = true;
    });
    var out = links.length ? 'Source: ' + links.join(' · ') : '';
    if (data) out += (out ? ' · ' : '') + 'From CageTime data: official UFC rankings, Tapology records and ESPN UFC stats (as of ' + esc(META.rankings_as_of || 'the last update') + ').';
    return out;
  }

  function pop(t) { var p = $('tv-pop'); p.textContent = t; p.classList.remove('go'); void p.offsetWidth; p.classList.add('go'); }

  function next() {
    if (!S) return;
    S.i++;
    if (S.i < S.qs.length) ask(); else finish();
  }

  function finish() {
    $('tv-prog').style.width = '100%';
    var seen = store.get('ct-trivia-seen', {}), keys;
    S.qs.forEach(function (q) { seen[q.id] = Date.now(); });
    keys = Object.keys(seen); if (keys.length > 700) { keys.sort(function (a, b) { return seen[a] - seen[b]; }).slice(0, keys.length - 700).forEach(function (k) { delete seen[k]; }); }
    store.set('ct-trivia-seen', seen);
    var newBest = false, best = store.get('ct-trivia-best', {});
    if (S.mode === 'daily') {
      var d = store.get('ct-trivia-daily', null);
      if (!d || d.date !== S.day) { store.set('ct-trivia-daily', { date: S.day, score: S.score, right: S.right }); newBest = true; }
      var db = best.daily || 0; if (S.score > db) { best.daily = S.score; store.set('ct-trivia-best', best); }
    } else if (S.score > (best[S.mode] || 0)) { best[S.mode] = S.score; store.set('ct-trivia-best', best); newBest = S.score > 0; }
    var grid = S.log.map(function (l) { return l.ok ? '🟩' : (l.timeout ? '⏱️' : '🟥'); }).join('');
    $('tv-rmode').textContent = S.mode === 'daily' ? 'Daily challenge · ' + S.day : MODES[S.mode].name + ' · x' + MODES[S.mode].mult;
    var title = S.right === S.qs.length ? 'Flawless victory' : S.right >= 8 ? 'Dominant performance' : S.right >= 6 ? 'Won on the cards' : S.right >= 4 ? 'Split decision' : 'Back to the gym';
    $('tv-rtitle').textContent = title;
    countUp($('tv-rscore'), S.score);
    $('tv-rline').textContent = S.right + ' of ' + S.qs.length + ' correct · best streak ' + S.best + (S.mode === 'daily' && !newBest ? ' · practice replay (first score of the day is kept)' : '');
    $('tv-rgrid').textContent = grid;
    var nb = $('tv-newbest'); nb.hidden = !newBest; nb.textContent = S.mode === 'daily' ? 'Daily score saved' : 'New personal best!';
    var share = (S.mode === 'daily' ? 'CageTime Daily UFC Trivia ' + S.day : 'CageTime UFC Trivia · ' + MODES[S.mode].name) + '\n' + grid + ' ' + S.right + '/' + S.qs.length +
      '\n' + fmt(S.score) + ' pts · best streak ' + S.best + '\nhttps://getcagetime.com/games/trivia/';
    $('tv-sharetext').value = share;
    $('tv-copied').textContent = '';
    $('tv-review').innerHTML = S.log.map(function (l) {
      return '<li><b>' + esc(l.q.q) + '</b><br><span class="' + (l.ok ? 'ok' : 'no') + '">' + (l.ok ? '✓ ' : '✗ ') + esc(l.pick == null ? 'No answer' : l.pick) + '</span>' + (l.ok ? '' : ' · answer: ' + esc(l.q.a)) + '</li>';
    }).join('');
    show('tv-results');
    sfx.done();
    if (S.right >= 8) confetti(S.right === S.qs.length ? 90 : 45);
  }

  function countUp(el, to) {
    var t0 = performance.now(), d = 900;
    (function f(now) { var k = Math.min(1, (now - t0) / d); el.textContent = fmt(to * (1 - Math.pow(1 - k, 3))); if (k < 1) requestAnimationFrame(f); })(t0);
  }
  function confetti(n) {
    if (matchMedia('(prefers-reduced-motion:reduce)').matches) return;
    var box = $('tv-confetti'), cols = ['#e5132b', '#f6c343', '#46d39a', '#6aa8ff', '#ececf1'];
    for (var i = 0; i < n; i++) {
      var p = document.createElement('i');
      p.style.left = (Math.random() * 100) + '%'; p.style.background = cols[i % cols.length];
      p.style.animationDuration = (1.6 + Math.random() * 1.8) + 's'; p.style.animationDelay = (Math.random() * 0.6) + 's';
      box.appendChild(p);
    }
    setTimeout(function () { box.innerHTML = ''; }, 4200);
  }

  function copyShare() {
    var txt = $('tv-sharetext').value, done = function () { $('tv-copied').textContent = 'Copied! Paste it anywhere.'; };
    var fallback = function () {
      var ta = $('tv-sharetext'); ta.focus(); ta.select();
      var ok = false; try { ok = document.execCommand('copy'); } catch (e) { ok = false; }
      $('tv-copied').textContent = ok ? 'Copied! Paste it anywhere.' : 'Select the text below and copy it.';
    };
    if (navigator.clipboard && window.isSecureContext) navigator.clipboard.writeText(txt).then(done, fallback); else fallback();
  }

  // ---------- wire up ----------
  document.querySelectorAll('.tv-mode').forEach(function (b) { b.addEventListener('click', function () { if (BANK.length) start(b.getAttribute('data-mode')); }); });
  $('tv-daily-btn').addEventListener('click', function () { if (BANK.length) start('daily'); });
  $('tv-next').addEventListener('click', next);
  $('tv-quit').addEventListener('click', function () { cancelAnimationFrame(timer); S = null; renderStart(); show('tv-start'); });
  $('tv-again').addEventListener('click', function () { start(S.mode); });
  $('tv-menu').addEventListener('click', function () { renderStart(); show('tv-start'); });
  $('tv-share').addEventListener('click', copyShare);
  $('tv-sound').addEventListener('click', function () { sound = !sound; store.set('ct-trivia-sound', sound); renderSound(); if (sound) sfx.right(); });
  document.addEventListener('keydown', function (e) {
    if (!$('tv-play').classList.contains('is-on') || !S || !S.cur || e.ctrlKey || e.metaKey || e.altKey) return;
    var k = e.key.toLowerCase(), idx = '1234'.indexOf(k) >= 0 ? '1234'.indexOf(k) : 'abcd'.indexOf(k);
    if (!S.cur.done && idx >= 0 && k.length === 1) { e.preventDefault(); answer(idx); }
    else if (S.cur.done && (k === 'enter' || k === ' ') && document.activeElement && document.activeElement.id !== 'tv-next') { e.preventDefault(); next(); }
  });

  fetch('questions.json?v=' + V).then(function (r) { if (!r.ok) throw new Error('questions.json ' + r.status); return r.json(); })
    .then(function (d) { BANK = d.questions || []; META = d.meta || {}; $('tv-upd').textContent = META.generated || '—'; renderStart(); document.body.setAttribute('data-ready', '1'); })
    .catch(function () { $('tv-bank').textContent = 'Could not load the questions. Please reload the page.'; });
  renderSound();
})();
